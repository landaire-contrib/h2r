"""Regenerate the Buck build rules from the Cargo manifests.

Run after any change to a Cargo.toml or Cargo.lock. `--check` exits 1 when
the committed rules differ from what it would write, and leaves them as they
are; `--first-party` skips Reindeer. Requires cargo, rustc and
reindeer on PATH (the devenv shell has them). Cargo.toml stays the source of
truth for crates, features and dependencies; Buck builds everything.

Third party: Reindeer does not follow the dev-dependencies of workspace
members, so it reads third-party/rust/Cargo.toml instead, a generated package
that depends on every external crate the workspace uses, at the resolved
version and with the features Cargo's resolver unified.

First party: one BUCK file per workspace member with its library, binaries,
build script, unit tests and integration tests (examples and benches are not
built). Each target compiles from a tree holding the crate's files at their
repository paths, plus the files of other packages its sources reach through
`../` (include_bytes!, #[path], build scripts that hash sibling crates).
"""

import json
import os
import re
import shutil
import subprocess
import sys
import tomllib

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THIRD_PARTY = os.path.join(REPO, "third-party", "rust")
MANIFEST = os.path.join(THIRD_PARTY, "Cargo.toml")
LOCK = os.path.join(THIRD_PARTY, "Cargo.lock")
BUCK = os.path.join(THIRD_PARTY, "BUCK")

# Platforms first-party `[target.'cfg(..)'.dependencies]` are evaluated for,
# keyed by the constraint a select() names.
PLATFORMS = {
    "config//os:linux": "x86_64-unknown-linux-gnu",
    "config//os:macos": "aarch64-apple-darwin",
    "config//os:windows": "x86_64-pc-windows-msvc",
}

# Paths excluded from a crate's library tree; test targets get everything.
TEST_ONLY_DIRS = ["tests", "benches", "examples"]

# Top-level paths never added to a crate tree: disc/ holds game data, and
# files directly under crates/ belong to no crate.
UNREACHABLE = {"buck-out", "crates", "disc", "target"}

THIRD_PARTY_HEADER = """\
# @generated by scripts/update-buck.py. Do not edit by hand.
# Every external dependency of the workspace, for Reindeer.

[package]
name = "third-party"
version = "0.0.0"
edition = "2024"
publish = false

[lib]
path = "lib.rs"

# Not a member of the repository workspace.
[workspace]
"""

FIRST_PARTY_HEADER = """\
# @generated by scripts/update-buck.py from Cargo.toml. Do not edit by hand.
"""


def run(args, **kwargs):
    return subprocess.run(args, cwd=REPO, check=True, **kwargs)


def starlark(value):
    return json.dumps(value)


def metadata():
    return json.loads(
        run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            capture_output=True,
            text=True,
        ).stdout
    )


class Workspace:
    def __init__(self, meta):
        self.packages = {p["id"]: p for p in meta["packages"]}
        self.members = set(meta["workspace_members"])
        self.nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        self.dirs = {
            pid: os.path.relpath(os.path.dirname(self.packages[pid]["manifest_path"]), REPO).replace(os.sep, "/")
            for pid in self.members
        }
        self.third_party_keys = self._third_party_keys()

    def _third_party_keys(self):
        """Dependency key in third-party/rust per external package id. A name
        used at two versions gets a version suffix on each."""
        used = {}
        for member in self.members:
            for dep in self.nodes[member]["deps"]:
                if dep["pkg"] not in self.members:
                    used.setdefault(self.packages[dep["pkg"]]["name"], set()).add(dep["pkg"])
        keys = {}
        for name, ids in used.items():
            for pid in ids:
                if len(ids) == 1:
                    keys[pid] = name
                else:
                    major, minor = self.packages[pid]["version"].split(".")[:2]
                    keys[pid] = "{}-{}_{}".format(name, major, minor)
        return keys

    def lib_target(self, pid):
        for target in self.packages[pid]["targets"]:
            if set(target["kind"]) & {"lib", "rlib", "proc-macro", "cdylib", "staticlib", "dylib"}:
                return target
        return None

    def label(self, pid):
        if pid in self.members:
            return "//{}:{}".format(self.dirs[pid], self.packages[pid]["name"])
        return "//third-party/rust:" + self.third_party_keys[pid]


def write_third_party_manifest(ws):
    sections = {}
    for pid, key in sorted(ws.third_party_keys.items(), key=lambda item: item[1]):
        package = ws.packages[pid]
        targets = set()
        for member in ws.members:
            for dep in ws.nodes[member]["deps"]:
                if dep["pkg"] == pid:
                    targets.update(kind["target"] for kind in dep["dep_kinds"])
        fields = ["version = " + starlark("=" + package["version"])]
        if key != package["name"]:
            fields.append("package = " + starlark(package["name"]))
        fields.append("default-features = false")
        features = sorted(ws.nodes[pid]["features"])
        if features:
            fields.append("features = [" + ", ".join(starlark(f) for f in features) + "]")
        line = "{} = {{ {} }}".format(key, ", ".join(fields))
        headers = ["[dependencies]"] if None in targets else [
            "[target.{}.dependencies]".format(starlark(target)) for target in sorted(targets)
        ]
        for header in headers:
            sections.setdefault(header, []).append(line)

    text = THIRD_PARTY_HEADER
    for header in sorted(sections, key=lambda h: (h != "[dependencies]", h)):
        text += "\n" + header + "\n" + "\n".join(sections[header]) + "\n"
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    with open(os.path.join(THIRD_PARTY, "lib.rs"), "w", encoding="utf-8", newline="\n") as f:
        f.write("")


def lock_packages(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    packages = set()
    for block in text.split("[[package]]")[1:]:
        name = re.search(r'^name = "([^"]+)"', block, re.M)
        version = re.search(r'^version = "([^"]+)"', block, re.M)
        source = re.search(r'^source = "([^"]+)"', block, re.M)
        if name and version and source:
            packages.add((name.group(1), version.group(1)))
    return packages


def flatten_multiline_env():
    # Buck spills long command lines into a line-oriented argument file, so an
    # argument containing a newline swallows the arguments after it.
    with open(BUCK, encoding="utf-8") as f:
        lines = f.read().split("\n")
    pattern = re.compile(r'"CARGO_PKG_(DESCRIPTION|AUTHORS)": ')
    lines = [re.sub(r"\\[rn]", " ", line) if pattern.search(line) else line for line in lines]
    with open(BUCK, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def update_third_party(ws):
    os.makedirs(THIRD_PARTY, exist_ok=True)
    write_third_party_manifest(ws)
    shutil.copyfile(os.path.join(REPO, "Cargo.lock"), LOCK)
    run(["reindeer", "buckify"])
    flatten_multiline_env()

    # The generated package may only drop entries from the workspace lock, never
    # resolve a version the workspace does not use.
    extra = lock_packages(LOCK) - lock_packages(os.path.join(REPO, "Cargo.lock"))
    if extra:
        sys.exit(
            "third-party/rust/Cargo.lock resolved packages absent from Cargo.lock:\n"
            + "".join("  {} {}\n".format(*p) for p in sorted(extra))
        )


class Cfg:
    """Evaluates Cargo `cfg(..)` target expressions against `rustc --print cfg`."""

    TOKEN = re.compile(r'\s*(?:(\()|(\))|(,)|(=)|"([^"]*)"|([A-Za-z_][A-Za-z0-9_]*))')

    def __init__(self):
        self.platforms = {}
        for constraint, triple in PLATFORMS.items():
            output = run(["rustc", "--print", "cfg", "--target", triple], capture_output=True, text=True).stdout
            values = set()
            for line in output.splitlines():
                key, _, value = line.partition("=")
                values.add((key, value.strip('"')) if value else (key, None))
            self.platforms[constraint] = (triple, values)

    def matches(self, target, constraint):
        triple, values = self.platforms[constraint]
        if not target.startswith("cfg("):
            return target == triple
        tokens = [m.groups() for m in self.TOKEN.finditer(target[len("cfg") :])]
        position, result = self._expr(tokens, 1, values)
        if position != len(tokens) - 1:
            sys.exit("unparsed cfg expression: " + target)
        return result

    def _expr(self, tokens, position, values):
        name = tokens[position][5]
        if name in ("all", "any", "not") and tokens[position + 1][0]:
            position += 2
            results = []
            while not tokens[position][1]:
                position, result = self._expr(tokens, position, values)
                results.append(result)
                if tokens[position][2]:
                    position += 1
            position += 1
            if name == "all":
                return position, all(results)
            if name == "any":
                return position, any(results)
            return position, not results[0]
        if position + 1 < len(tokens) and tokens[position + 1][3]:
            return position + 3, (name, tokens[position + 2][4]) in values
        return position + 1, (name, None) in values


def literal_paths(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()
    return re.findall(r'"(/?\.\./[^"\n]*)"', text)


def is_test_only(relpath):
    return relpath.split("/")[0] in TEST_ONLY_DIRS


class Crate:
    def __init__(self, ws, pid, cfg):
        self.ws = ws
        self.pid = pid
        self.cfg = cfg
        self.package = ws.packages[pid]
        self.dir = ws.dirs[pid]
        self.abs_dir = os.path.join(REPO, self.dir)
        self.name = self.package["name"]
        self.version = self.package["version"]
        self.features = sorted(ws.nodes[pid]["features"])
        self.description = " ".join((self.package.get("description") or "").split())
        with open(self.package["manifest_path"], "rb") as f:
            self.manifest = tomllib.load(f)
        self.lib = ws.lib_target(pid)
        self.build_script = next((t for t in self.package["targets"] if "custom-build" in t["kind"]), None)
        self.lib_reach, self.test_reach = self._reach()

    def rel(self, path):
        return os.path.relpath(path, self.abs_dir).replace(os.sep, "/")

    def _sources(self):
        nested = {os.path.join(REPO, d) for pid, d in self.ws.dirs.items() if pid != self.pid}
        for root, dirs, files in os.walk(self.abs_dir):
            dirs[:] = [d for d in dirs if os.path.join(root, d) not in nested and d != "target"]
            for file in files:
                if file.endswith(".rs"):
                    yield os.path.join(root, file)

    def _owner(self, path):
        """The files target that holds repository path `path`, or None."""
        best = None
        for pid, directory in self.ws.dirs.items():
            if (path + "/").startswith(directory + "/") and (best is None or len(directory) > len(self.ws.dirs[best])):
                best = pid
        if best is None:
            top = path.split("/")[0]
            return None if top in UNREACHABLE else "//:" + top
        inner = path[len(self.ws.dirs[best]) + 1 :]
        part = "all" if is_test_only(inner) else "src"
        return "//{}:{}".format(self.ws.dirs[best], part)

    def _reach(self):
        # Exact paths outside crates/ that sources name, for root exports.
        self.root_paths = set()
        lib, tests = set(), set()
        for source in self._sources():
            test_only = is_test_only(self.rel(source))
            for literal in literal_paths(source):
                for base in (os.path.dirname(source), self.abs_dir):
                    target = os.path.normpath(os.path.join(base, literal.lstrip("/")))
                    if not os.path.exists(target):
                        continue
                    relpath = os.path.relpath(target, REPO).replace(os.sep, "/")
                    if relpath.startswith("..") or (relpath + "/").startswith(self.dir + "/"):
                        break
                    # An ancestor directory (`../../..` naming the repo root),
                    # or game data, which never enters the build graph.
                    if (self.dir + "/").startswith(relpath + "/") or relpath == ".":
                        break
                    owner = self._owner(relpath)
                    if owner is not None:
                        (tests if test_only else lib).add(owner)
                        if owner.startswith("//:"):
                            self.root_paths.add(relpath)
                    break
        return lib, tests | lib

    def deps(self, kinds, self_lib):
        """Unconditional deps, select() branches and named deps for `kinds`."""
        plain, conditional, named = set(), {}, {}
        for dep in self.ws.nodes[self.pid]["deps"]:
            targets = {kind["target"] for kind in dep["dep_kinds"] if kind["kind"] in kinds}
            if not targets:
                continue
            label = self.ws.label(dep["pkg"])
            hits = list(PLATFORMS) if None in targets else [
                c for c in PLATFORMS if any(self.cfg.matches(t, c) for t in targets)
            ]
            if not hits:
                continue
            lib = self.ws.lib_target(dep["pkg"])
            if lib is not None and dep["name"] != lib["name"].replace("-", "_"):
                if len(hits) != len(PLATFORMS):
                    sys.exit("{}: platform-specific renamed dependency {} is unsupported".format(self.name, dep["name"]))
                named[dep["name"]] = label
                continue
            if len(hits) == len(PLATFORMS):
                plain.add(label)
                continue
            for constraint in hits:
                conditional.setdefault(constraint, set()).add(label)
        if self_lib and self.lib is not None:
            plain.add(":" + self.name)
        return plain, conditional, named

    def dev_opt_level(self):
        with open(os.path.join(REPO, "Cargo.toml"), "rb") as f:
            root = tomllib.load(f)
        level = root.get("profile", {}).get("dev", {}).get("package", {}).get(self.name, {}).get("opt-level")
        return level

    def has_required_features(self, target):
        for entry in self.manifest.get("bin", []) + self.manifest.get("test", []):
            if entry.get("name") == target["name"]:
                return all(f in self.features for f in entry.get("required-features", []))
        return True

    def render(self):
        out = [FIRST_PARTY_HEADER]
        out.append(
            'load("//build-support/buck:workspace_rules.bzl", "crate_files", "crate_tree", '
            '"workspace_binary", "workspace_buildscript", "workspace_library", "workspace_test")\n'
        )
        excludes = ["BUCK"] + [d + "/**" for d in TEST_ONLY_DIRS]
        out.append(
            'crate_files(\n    name = "src",\n    srcs = glob(["**"], exclude = {}),\n    visibility = ["PUBLIC"],\n)\n'.format(
                starlark(excludes)
            )
        )
        out.append('crate_files(\n    name = "all",\n    srcs = glob(["**"], exclude = ["BUCK"]),\n    visibility = ["PUBLIC"],\n)\n')
        out.append(self._tree("lib-tree", [":src"] + sorted(self.lib_reach)))
        out.append(self._tree("test-tree", [":all"] + sorted(self.test_reach)))

        common = {
            "package": self.name,
            "version": self.version,
            "manifest": self.dir,
        }
        buildscript = None
        if self.build_script is not None:
            plain, conditional, named = self.deps({"build"}, False)
            out.append(
                self._call(
                    "workspace_buildscript",
                    "build-script",
                    common | {"tree": ":lib-tree", "features": self.features},
                    plain,
                    conditional,
                    named,
                )
            )
            buildscript = ":build-script"

        level = self.dev_opt_level()
        shared = {"description": self.description, "features": self.features}
        if buildscript:
            shared["buildscript"] = buildscript
        if level is not None:
            shared["dev_opt_level"] = level

        binaries = {}
        for target in self.package["targets"]:
            if "bin" in target["kind"] and self.has_required_features(target):
                binaries[target["name"]] = ":" + self._bin_name(target["name"])

        if self.lib is not None:
            plain, conditional, named = self.deps({None}, False)
            attrs = common | shared | {
                "crate": self.lib["name"].replace("-", "_"),
                "crate_root": self._root(self.lib),
                "tree": ":lib-tree",
            }
            out.append(self._call("workspace_library", self.name, attrs, plain, conditional, named))
            if self.lib["test"]:
                plain, conditional, named = self.deps({None, "dev"}, False)
                attrs = attrs | {"tree": ":test-tree"}
                out.append(self._call("workspace_test", "unit-tests", attrs, plain, conditional, named))

        for target in self.package["targets"]:
            if "bin" not in target["kind"] or not self.has_required_features(target):
                continue
            name = self._bin_name(target["name"])
            plain, conditional, named = self.deps({None}, True)
            attrs = common | shared | {
                "crate": target["name"].replace("-", "_"),
                "crate_root": self._root(target),
                "tree": ":lib-tree",
            }
            out.append(self._call("workspace_binary", name, attrs, plain, conditional, named))
            if target["test"]:
                plain, conditional, named = self.deps({None, "dev"}, True)
                attrs = attrs | {"tree": ":test-tree"}
                out.append(self._call("workspace_test", name + "-unit-tests", attrs, plain, conditional, named))

        for target in self.package["targets"]:
            if "test" not in target["kind"] or not self.has_required_features(target):
                continue
            plain, conditional, named = self.deps({None, "dev"}, True)
            attrs = common | shared | {
                "crate": target["name"].replace("-", "_"),
                "crate_root": self._root(target),
                "tree": ":test-tree",
            }
            if binaries:
                attrs["binaries"] = binaries
            out.append(self._call("workspace_test", self._test_name(target["name"]), attrs, plain, conditional, named))
        return "\n".join(out)

    def _bin_name(self, name):
        return name + "-bin" if self.lib is not None and name == self.name else name

    def _test_name(self, name):
        taken = {self.name, "unit-tests", "src", "all", "lib-tree", "test-tree", "build-script"}
        taken.update(t["name"] for t in self.package["targets"] if "bin" in t["kind"])
        return name + "-test" if name in taken else name

    def _root(self, target):
        return os.path.relpath(target["src_path"], REPO).replace(os.sep, "/")

    def _tree(self, name, files):
        return 'crate_tree(\n    name = {},\n    files = {},\n)\n'.format(starlark(name), self._list(files, 4))

    def _list(self, items, indent):
        items = list(items)
        if not items:
            return "[]"
        pad = " " * (indent + 4)
        return "[\n" + "".join(pad + starlark(i) + ",\n" for i in items) + " " * indent + "]"

    def _call(self, function, name, attrs, plain, conditional, named):
        lines = ["{}(".format(function), "    name = {},".format(starlark(name))]
        for key in sorted(attrs):
            value = attrs[key]
            if isinstance(value, list):
                lines.append("    {} = {},".format(key, self._list(value, 4)))
            elif isinstance(value, dict):
                body = "".join("        {}: {},\n".format(starlark(k), starlark(v)) for k, v in sorted(value.items()))
                lines.append("    {} = {{\n{}    }},".format(key, body))
            else:
                lines.append("    {} = {},".format(key, starlark(value)))
        deps = self._list(sorted(plain), 4)
        if conditional:
            branches = "".join(
                "        {}: {},\n".format(starlark(c), self._list(sorted(conditional[c]), 8)) for c in sorted(conditional)
            )
            deps += " + select({{\n{}        \"DEFAULT\": [],\n    }})".format(branches)
        lines.append("    deps = {},".format(deps))
        if named:
            body = "".join("        {}: {},\n".format(starlark(k), starlark(v)) for k, v in sorted(named.items()))
            lines.append("    named_deps = {{\n{}    }},".format(body))
        lines.append(")\n")
        return "\n".join(lines)


def visible_files(paths):
    """Tracked and untracked files under `paths` that git does not ignore.
    Ignored paths hold build output and game-derived captures (README frames),
    which never enter a crate tree."""
    output = run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", *paths],
        capture_output=True,
        text=True,
    ).stdout
    return sorted({f for f in output.split("\0") if f and os.path.isfile(os.path.join(REPO, f))})


def write_root_exports(crates):
    """Filegroups of the files outside crates/ that crate trees reach, one per
    top-level directory, listing exactly the named paths."""
    paths = {}
    for crate in crates:
        for path in crate.root_paths:
            paths.setdefault(path.split("/")[0], set()).add(path)
    out = os.path.join(REPO, "build-support", "buck", "root_exports.bzl")
    lines = [
        "# @generated by scripts/update-buck.py. Do not edit by hand.",
        'load("//build-support/buck:workspace_rules.bzl", "crate_files")',
        "",
        "def root_exports():",
        '    """Files outside crates/ that crate trees include."""',
    ]
    for top in sorted(paths):
        files = visible_files(sorted(paths[top]))
        body = "".join("            {},\n".format(starlark(f)) for f in files)
        lines.append(
            "    crate_files(\n        name = {},\n        srcs = [\n{}        ],\n        visibility = [\"PUBLIC\"],\n    )".format(
                starlark(top), body
            )
        )
    if not paths:
        lines.append("    pass")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def update_first_party(ws):
    cfg = Cfg()
    crates = [Crate(ws, pid, cfg) for pid in sorted(ws.members, key=lambda p: ws.dirs[p])]
    for crate in crates:
        with open(os.path.join(crate.abs_dir, "BUCK"), "w", encoding="utf-8", newline="\n") as f:
            f.write(crate.render())
    write_root_exports(crates)


def generated_files():
    """Every file this script writes, with its current contents."""
    paths = [
        os.path.join(THIRD_PARTY, name) for name in ("BUCK", "Cargo.toml", "Cargo.lock", "lib.rs")
    ] + [os.path.join(REPO, "build-support", "buck", "root_exports.bzl")]
    for root, dirs, files in os.walk(os.path.join(REPO, "crates")):
        dirs[:] = [d for d in dirs if d != "target"]
        if "BUCK" in files:
            paths.append(os.path.join(root, "BUCK"))
    contents = {}
    for path in paths:
        if os.path.exists(path):
            with open(path, "rb") as f:
                contents[path] = f.read()
    return contents


def restore(contents):
    for path in set(generated_files()) - set(contents):
        os.remove(path)
    for path, data in contents.items():
        with open(path, "wb") as f:
            f.write(data)


def main():
    check = "--check" in sys.argv
    before = generated_files() if check else None
    ws = Workspace(metadata())
    if "--first-party" not in sys.argv:
        update_third_party(ws)
    update_first_party(ws)
    if not check:
        return 0

    # --check: regenerate, report what differs, and put the old files back.
    after = generated_files()
    restore(before)
    stale = sorted(os.path.relpath(p, REPO) for p in set(before) | set(after) if before.get(p) != after.get(p))
    if stale:
        print("Buck rules are stale; run scripts/update-buck.py:\n" + "".join("  {}\n".format(p) for p in stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
